// Build crates/vic3-api/playbook/ui_terms.toml from the game's English and Polish
// localization: each interface label the advice steps name, in both languages.
// Usage: node ui_terms.js "<Victoria 3 folder>" <out.toml>
const fs = require("fs");
const path = require("path");
const [game, out] = process.argv.slice(2);
const KEYS = [
  "SETTING_INPUT_ACTION_OPEN_BUDGET", "SETTING_INPUT_ACTION_OPEN_POLITICS",
  "SETTING_INPUT_ACTION_OPEN_MARKET", "SETTING_INPUT_ACTION_OPEN_TECHNOLOGY", "SETTING_INPUT_ACTION_OPEN_MILITARY",
  "SETTING_INPUT_ACTION_OPEN_JOURNAL", "CONSTRUCTION", "COUNTRY_PANEL_DIPLOMACY_TAB", "MILITARY_FORMATION_PANEL_BUILDINGS_TAB", "DECISIONS", "LAWS",
  "BUILDING_PANEL_EXPAND", "BUILDING_PANEL_DOWNSIZE", "CANCEL_CONSTRUCTION", "REFORM_GOVERNMENT", "ADD_TO_GOVERNMENT",
  "REMOVE_FROM_GOVERNMENT", "ENACT", "MILITARY_FORMATION_DISBAND", "DEMOBILIZE_ALL_MILITARY_FORMATIONS",
  "MILITARY_FORMATION_ARMY_BUILDINGS", "MILITARY_FORMATION_UNITS", "TARIFFS", "DIPLOMATIC_ACTIONS",
  "concept_budget_military_wages", "concept_budget_government_wages", "concept_interest_groups", "concept_institutions",
  "concept_diplomatic_play", "concept_production_methods", "concept_construction_queue", "concept_tax_level",
  "concept_budget_consumption_taxes",
];
function load(lang) {
  const dir = path.join(game, "game", "localization", lang);
  const map = {};
  const walk = (d) => {
    for (const f of fs.readdirSync(d)) {
      const p = path.join(d, f);
      if (fs.statSync(p).isDirectory()) walk(p);
      else if (f.endsWith(".yml")) {
        for (const line of fs.readFileSync(p, "utf8").split("\n")) {
          const m = line.match(/^ ([A-Za-z0-9_.]+):\d* "(.*)"\s*$/);
          if (m && !(m[1] in map)) map[m[1]] = m[2];
        }
      }
    }
  };
  walk(dir);
  return map;
}
function resolve(map, text, depth = 0) {
  if (text === undefined || depth > 4) return text;
  return text
    .replace(/\$([A-Za-z0-9_]+)\$/g, (_, k) => resolve(map, map[k], depth + 1) ?? k)
    .replace(/\[concept_([a-z0-9_]+)\]/g, (_, k) => resolve(map, map["concept_" + k], depth + 1) ?? k)
    .replace(/#[a-z_]+ |#!|@[a-z_]+!/g, "");
}
const en = load("english");
const pl = load("polish");
const rows = [];
for (const k of KEYS) {
  const e = resolve(en, en[k]);
  const p = resolve(pl, pl[k]);
  if (!e || !p) {
    console.error("missing", k, e, p);
    continue;
  }
  rows.push(`[[term]]\nkey = "${k}"\nen = ${JSON.stringify(e)}\npl = ${JSON.stringify(p)}\n`);
}
const header = "# Interface labels the advice steps name, English and Polish, from the 1.13.9 game\n# localization (generated by a script from game/localization; keys are the game's).\n\n";
fs.writeFileSync(out, header + rows.join("\n"));
console.log(rows.length, "terms");
